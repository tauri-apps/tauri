//! Experimental C ABI for embedding Tauri from non-Rust hosts (C, Node.js,
//! Python, Deno, …). M0 spike of `/ffi-bindings-plan.md`.
//!
//! # Conventions
//! - Every fallible function returns `i32` (`0` = ok, negative = error class)
//!   with out-values through pointer params. Details via
//!   [`tauri_last_error_message`].
//! - Objects are opaque `u64` handles (0 is never valid).
//! - Structured data crosses the boundary as UTF-8 JSON strings.
//! - Strings returned through `char**` out params are owned by the caller and
//!   must be released with [`tauri_string_free`].
//!
//! # Threading
//! - [`tauri_app_build`] and [`tauri_app_run`] must be called on the same
//!   thread — the process main thread on macOS. `tauri_app_run` blocks until
//!   the app exits (it wraps `App::run_return`).
//! - Everything else may be called from any thread; events are consumed by
//!   polling [`tauri_events_next`] from any thread (typically not the one
//!   blocked in `run`).
#![allow(clippy::missing_safety_doc)] // TODO(M1): per-fn safety docs, generated into the header

