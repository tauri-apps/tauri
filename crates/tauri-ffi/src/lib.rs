// run loop

/// Runs the event loop, blocking the calling thread until the app exits.
/// Must be called on the thread that called `tauri_app_build`. Run events are
/// also delivered through the event queue (`{"type":"ready"}`, `"exit"`, …).
#[no_mangle]
pub unsafe extern "C" fn tauri_app_run(app: u64, out_exit_code: *mut i32) -> i32 {
  catch(|| {
    let Some(local_app) = state::LOCAL_APPS.with(|apps| apps.borrow_mut().remove(&app)) else {
      return fail(
        ERR_INVALID_HANDLE,
        "unknown app handle — tauri_app_run must be called on the thread that called tauri_app_build",
      );
    };
    let Some(app_state) = state::app(app) else {
      return fail(ERR_INVALID_HANDLE, "invalid app handle");
    };
    let tx = app_state.tx.clone();
    drop(app_state);

    let exit_code = local_app.run_return(move |_handle, event| {
      if let Some(message) = run_event_json(&event) {
        let _ = tx.send(message);
      }
    });

    if !out_exit_code.is_null() {
      unsafe { *out_exit_code = exit_code };
    }
    OK
  })
}

/// Requests app exit from any thread.
#[no_mangle]
pub extern "C" fn tauri_app_exit(app: u64, code: i32) -> i32 {
  catch(|| {
    let Some(app_state) = state::app(app) else {
      return fail(ERR_INVALID_HANDLE, "invalid app handle");
    };
    app_state.handle.exit(code);
    OK
  })
}

fn run_event_json(event: &RunEvent) -> Option<String> {
  let value = match event {
    RunEvent::Ready => serde_json::json!({ "type": "ready" }),
    RunEvent::Exit => serde_json::json!({ "type": "exit" }),
    RunEvent::ExitRequested { code, .. } => {
      // Queue consumers cannot veto synchronously; exit policies are the
      // M1 answer (see plan §4.4).
      serde_json::json!({ "type": "exit-requested", "code": code })
    }
    RunEvent::WindowEvent { label, event, .. } => {
      let window_event = match event {
        WindowEvent::CloseRequested { .. } => serde_json::json!({ "kind": "close-requested" }),
        WindowEvent::Destroyed => serde_json::json!({ "kind": "destroyed" }),
        WindowEvent::Focused(focused) => {
          serde_json::json!({ "kind": "focused", "focused": focused })
        }
        WindowEvent::Moved(position) => {
          serde_json::json!({ "kind": "moved", "x": position.x, "y": position.y })
        }
        WindowEvent::Resized(size) => {
          serde_json::json!({ "kind": "resized", "width": size.width, "height": size.height })
        }
        _ => return None,
      };
      serde_json::json!({ "type": "window-event", "label": label, "event": window_event })
    }
    _ => return None,
  };
  Some(value.to_string())
}

// ---------------------------------------------------------------------------
// event queue

/// Blocks up to `timeout_ms` for the next queued message (run events,
/// subscribed events, invokes). On `TAURI_OK`, `*out_json` is an owned string
/// — free it with `tauri_string_free`. Returns `ERR_TIMEOUT` (-3) on timeout
/// and `ERR_CLOSED` (-4) once the app has shut down.
#[no_mangle]
pub unsafe extern "C" fn tauri_events_next(
  app: u64,
  timeout_ms: u32,
  out_json: *mut *mut c_char,
) -> i32 {
  catch(|| {
    if out_json.is_null() {
      return fail(ERR_INVALID_ARG, "out_json is null");
    }
    let Some(app_state) = state::app(app) else {
      return fail(ERR_INVALID_HANDLE, "invalid app handle");
    };
    let rx = app_state.rx.lock().unwrap();
    match rx.recv_timeout(Duration::from_millis(timeout_ms.into())) {
      Ok(message) => {
        write_owned_str(out_json, message);
        OK
      }
      Err(mpsc::RecvTimeoutError::Timeout) => ERR_TIMEOUT,
      Err(mpsc::RecvTimeoutError::Disconnected) => ERR_CLOSED,
    }
  })
}

