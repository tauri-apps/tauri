/// Creates an app builder from a `tauri.conf.json`-shaped JSON string.
#[no_mangle]
pub unsafe extern "C" fn tauri_app_builder_new(
  config_json: *const c_char,
  out_builder: *mut u64,
) -> i32 {
  catch(|| {
    let json = try_cstr!(config_json);
    if out_builder.is_null() {
      return fail(ERR_INVALID_ARG, "out_builder is null");
    }
    let config: Config = match serde_json::from_str(json) {
      Ok(config) => config,
      Err(e) => return fail(ERR_INVALID_ARG, format!("invalid config: {e}")),
    };
    let id = state::insert(Entry::Builder(BuilderState {
      config,
      assets_dir: None,
      commands: Default::default(),
      capabilities: Vec::new(),
      plugins: Vec::new(),
    }));
    unsafe { *out_builder = id };
    OK
  })
}

/// Serves the app frontend (`WebviewUrl::App` paths) from a directory.
#[no_mangle]
pub unsafe extern "C" fn tauri_app_builder_set_assets_dir(
  builder: u64,
  path: *const c_char,
) -> i32 {
  catch(|| {
    let path = try_cstr!(path);
    state::with_builder(builder, |b| {
      b.assets_dir = Some(path.into());
      OK
    })
  })
}

/// Registers a command name; invokes for it are delivered through
/// `tauri_events_next` as `{"type":"invoke",...}` messages.
#[no_mangle]
pub unsafe extern "C" fn tauri_app_builder_register_command(
  builder: u64,
  name: *const c_char,
) -> i32 {
  catch(|| {
    let name = try_cstr!(name);
    state::with_builder(builder, |b| {
      b.commands.insert(name.to_string());
      OK
    })
  })
}

/// Adds a capability (JSON or TOML string, same format as capability files).
/// If none is added, a default granting `core:default` to all windows is used.
#[no_mangle]
pub unsafe extern "C" fn tauri_app_builder_add_capability(
  builder: u64,
  capability: *const c_char,
) -> i32 {
  catch(|| {
    let capability = try_cstr!(capability);
    state::with_builder(builder, |b| {
      b.capabilities.push(capability.to_string());
      OK
    })
  })
}

/// Consumes the builder and builds the app. Must be called on the thread that
/// will run the event loop (the process main thread on macOS). Windows
/// declared in the config are created when the app runs.
#[no_mangle]
pub unsafe extern "C" fn tauri_app_build(builder: u64, out_app: *mut u64) -> i32 {
  catch(|| {
    if out_app.is_null() {
      return fail(ERR_INVALID_ARG, "out_app is null");
    }
    let Some(Entry::Builder(builder_state)) = state::remove(builder) else {
      return fail(ERR_INVALID_HANDLE, "invalid builder handle");
    };
    match build_app(builder_state) {
      Ok(id) => {
        unsafe { *out_app = id };
        OK
      }
      Err(message) => fail(ERR_GENERIC, message),
    }
  })
}

fn build_app(builder_state: BuilderState) -> Result<u64, String> {
  let BuilderState {
    config,
    assets_dir,
    commands,
    capabilities,
    plugins,
  } = builder_state;

  // ACL: embedded core manifests + a synthesized manifest per host plugin so
  // its `plugin:<name>|<command>` invokes resolve at runtime (`dynamic-acl`).
  let mut acl: BTreeMap<String, Manifest> = serde_json::from_str(ACL_MANIFESTS_JSON)
    .map_err(|e| format!("corrupt embedded ACL manifests: {e}"))?;
  for plugin in &plugins {
    acl.insert(plugin.name.clone(), plugin_manifest(plugin));
  }
  let plugin_names: Vec<String> = plugins.iter().map(|p| p.name.clone()).collect();
  let authority = tauri::runtime_authority!(acl, Resolved::default());

  let assets: Box<dyn tauri::Assets<Wry>> = match assets_dir {
    Some(dir) => Box::new(assets::DirAssets::new(dir)),
    None => Box::new(assets::EmptyAssets),
  };

  let package_info = PackageInfo {
    name: config
      .product_name
      .clone()
      .unwrap_or_else(|| "Tauri App".into()),
    version: config
      .version
      .as_deref()
      .unwrap_or("0.1.0")
      .parse()
      .map_err(|e| format!("invalid config version: {e}"))?,
    authors: "",
    description: "",
    crate_name: "tauri-ffi",
  };

  let global_api_scripts = (config.app.with_global_tauri && !GLOBAL_API_SCRIPTS.is_empty())
    .then_some(GLOBAL_API_SCRIPTS);

  let context = tauri::Context::<Wry>::new(
    config,
    assets,
    None, // default window icon — TODO(M1): tauri_app_builder_set_icon_rgba
    None, // app icon
    package_info,
    Pattern::Brownfield,
    authority,
    global_api_scripts,
  );

  // Serialized event stream: run events, subscribed events and invokes all
  // flow through one queue consumed by `tauri_events_next`.
  let (tx, rx) = mpsc::channel::<String>();

  let invoke_tx = tx.clone();
  let mut builder = tauri::Builder::default().invoke_handler(
    move |invoke: tauri::ipc::Invoke<Wry>| {
      let command = invoke.message.command();
      if !commands.contains(command) {
        return false; // tauri reports "command not found" to the frontend
      }
      let _ = invoke_tx.send(invoke_message_json(&invoke, command, None));
      true
    },
  );

  // Each plugin gets a `tauri::plugin::Builder` whose invoke handler funnels
  // into the same event queue, tagged with the plugin name.
  for plugin in plugins {
    let state::PluginState {
      name,
      init_script,
      commands: plugin_commands,
    } = plugin;
    let plugin_tx = tx.clone();
    let plugin_name = name.clone();
    // `plugin::Builder::new` wants a `&'static str`; a plugin is created once
    // for the life of the app, so a one-time leak is acceptable.
    let leaked_name: &'static str = Box::leak(name.into_boxed_str());
    let mut plugin_builder = tauri::plugin::Builder::<Wry>::new(leaked_name).invoke_handler(
      move |invoke: tauri::ipc::Invoke<Wry>| {
        // tauri strips the `plugin:<name>|` prefix before dispatch, so
        // `command()` is the bare command name here.
        let command = invoke.message.command();
        if !plugin_commands.contains(command) {
          return false;
        }
        let _ = plugin_tx.send(invoke_message_json(&invoke, command, Some(&plugin_name)));
        true
      },
    );
    if let Some(js) = init_script {
      plugin_builder = plugin_builder.js_init_script(js);
    }
    let plugin = plugin_builder
      .try_build()
      .map_err(|e| format!("invalid plugin `{leaked_name}`: {e}"))?;
    builder = builder.plugin(plugin);
  }

  let app = builder
    .build(context)
    .map_err(|e| format!("failed to build app: {e}"))?;

  let handle = app.handle().clone();

  let mut capabilities = if capabilities.is_empty() {
    vec![DEFAULT_CAPABILITY.to_string()]
  } else {
    capabilities
  };
  // Grant every registered plugin's default permission to all windows — the
  // host opted in by registering the plugin's commands.
  if !plugin_names.is_empty() {
    let permissions: Vec<String> = plugin_names.iter().map(|n| format!("{n}:default")).collect();
    capabilities.push(
      serde_json::json!({
        "identifier": "tauri-ffi-plugins-default",
        "description": "Grants FFI-registered plugin default permissions to all windows.",
        "windows": ["*"],
        "permissions": permissions,
      })
      .to_string(),
    );
  }
  for capability in capabilities {
    handle
      .add_capability(capability)
      .map_err(|e| format!("invalid capability: {e}"))?;
  }

  let id = state::insert(Entry::App(Arc::new(AppState {
    handle,
    rx: Mutex::new(rx),
    tx,
  })));
  state::LOCAL_APPS.with(|apps| apps.borrow_mut().insert(id, app));
  Ok(id)
}

/// Registers the invoke's resolver and serializes it into a queue message.
/// `plugin` is `Some` for plugin commands (adds a `"plugin"` field).
fn invoke_message_json(invoke: &tauri::ipc::Invoke<Wry>, command: &str, plugin: Option<&str>) -> String {
  let payload = match invoke.message.payload() {
    InvokeBody::Json(value) => value.clone(),
    // TODO(M1): raw (binary) payloads
    InvokeBody::Raw(_) => serde_json::Value::Null,
  };
  let resolver_id = state::insert(Entry::Resolver(invoke.resolver.clone()));
  let mut message = serde_json::json!({
    "type": "invoke",
    "id": resolver_id,
    "command": command,
    "payload": payload,
    "webview": invoke.message.webview_ref().label(),
  });
  if let Some(plugin) = plugin {
    message["plugin"] = serde_json::Value::String(plugin.to_string());
  }
  message.to_string()
}

/// Synthesizes an ACL manifest granting a host plugin's commands. The default
/// permission `<name>:default` (referenced by the default capability) allows
/// every registered command, so `plugin:<name>|<command>` resolves at runtime.
fn plugin_manifest(plugin: &state::PluginState) -> Manifest {
  use tauri::utils::acl::manifest::{DefaultPermission, PermissionFile};
  use tauri::utils::acl::{Commands, Permission};

  let commands = plugin.commands.iter().cloned().collect();
  let permission = Permission {
    version: None,
    identifier: "allow-all".to_string(),
    description: None,
    commands: Commands {
      allow: commands,
      deny: Vec::new(),
    },
    scope: Default::default(),
    platforms: None,
  };
  let file = PermissionFile {
    default: Some(DefaultPermission {
      version: None,
      description: None,
      permissions: vec!["allow-all".to_string()],
    }),
    set: Vec::new(),
    permission: vec![permission],
  };
  Manifest::new(vec![file], None)
}

