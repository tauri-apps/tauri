/// Resolves a pending invoke with a JSON value. Consumes the resolver handle.
/// Callable from any thread, any time after the invoke was delivered.
#[no_mangle]
pub unsafe extern "C" fn tauri_invoke_resolve(resolver: u64, json: *const c_char) -> i32 {
  catch(|| {
    let json = try_cstr!(json);
    let Some(Entry::Resolver(resolver)) = state::remove(resolver) else {
      return fail(ERR_INVALID_HANDLE, "invalid resolver handle");
    };
    resolver.respond(Ok::<_, InvokeError>(InvokeResponseBody::Json(
      json.to_owned(),
    )));
    OK
  })
}

/// Rejects a pending invoke with a JSON value. Consumes the resolver handle.
#[no_mangle]
pub unsafe extern "C" fn tauri_invoke_reject(resolver: u64, json: *const c_char) -> i32 {
  catch(|| {
    let json = try_cstr!(json);
    let Some(Entry::Resolver(resolver)) = state::remove(resolver) else {
      return fail(ERR_INVALID_HANDLE, "invalid resolver handle");
    };
    let value: serde_json::Value =
      serde_json::from_str(json).unwrap_or_else(|_| serde_json::Value::String(json.to_owned()));
    resolver.respond(Err::<InvokeResponseBody, _>(InvokeError(value)));
    OK
  })
}
