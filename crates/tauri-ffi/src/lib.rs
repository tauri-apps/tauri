/// Consumes the builder and builds the app. Must be called on the thread that
/// will run the event loop (the process main thread on macOS). Windows
/// declared in the config are created when the app runs.
#[no_mangle]
pub unsafe extern "C" fn tauri_app_build(builder: u64, out_app: *mut u64) -> i32 {
  catch(|| {
    if out_app.is_null() {
      return fail(ERR_INVALID_ARG, "out_app is null");
    }
    let Some(Entry::Builder(builder_state)) = state::remove(builder) else {
      return fail(ERR_INVALID_HANDLE, "invalid builder handle");
    };
    match build_app(*builder_state) {
      Ok(id) => {
        unsafe { *out_app = id };
        OK
      }
      Err(message) => fail(ERR_GENERIC, message),
    }
  })
}

fn build_app(builder_state: BuilderState) -> Result<u64, String> {
  let BuilderState {
    mut config,
    assets_dir,
    assets_archive,
    assets_archive_bytes,
    dev,
    commands,
    capabilities,
    plugins,
    uri_scheme_protocols,
    invoke_initialization_scripts,
    device_event_filter,
    macos_default_menu,
    default_window_icon,
    app_icon,
    any_thread,
    localhost_port,
    single_instance,
    page_load_events,
    webview_events,
  } = builder_state;

  // Dev-mode emulation: the prebuilt cdylib is not compiled with the `dev`
  // cfg, but the runtime resolves `WebviewUrl::App` (and the Local origin for
  // ACL checks) against `frontend_dist` when it is a URL — so pointing it at
  // `devUrl` reproduces exactly what a Rust dev build does.
  if dev {
    if let Some(dev_url) = config.build.dev_url.clone() {
      config.build.frontend_dist = Some(tauri::utils::config::FrontendDist::Url(dev_url));
    }
  }

  // `cli` and `updater` read a required `plugins.<name>` config section and
  // fail app startup if it is absent (their config deserializes from `null`
  // and errors), so they are only registered when the host configured them.
  // Captured here because `config` is moved into the `Context` below.
  let cli_configured = config.plugins.0.contains_key("cli");
  let updater_configured = config.plugins.0.contains_key("updater");

  // ACL: embedded core manifests + a synthesized manifest per host plugin so
  // its `plugin:<name>|<command>` invokes resolve at runtime (`dynamic-acl`).
  let mut acl: BTreeMap<String, Manifest> = serde_json::from_str(ACL_MANIFESTS_JSON)
    .map_err(|e| format!("corrupt embedded ACL manifests: {e}"))?;
  for plugin in &plugins {
    acl.insert(plugin.name.clone(), plugin_manifest(plugin));
  }
  let plugin_names: Vec<String> = plugins.iter().map(|p| p.name.clone()).collect();
  let authority = tauri::runtime_authority!(acl, Resolved::default());

  let assets: Box<dyn tauri::Assets<TauriRuntime>> = if let Some(bytes) = assets_archive_bytes {
    Box::new(assets::ArchiveAssets::from_bytes(bytes)?)
  } else if let Some(archive) = assets_archive {
    Box::new(assets::ArchiveAssets::load(&archive)?)
  } else if let Some(dir) = assets_dir {
    Box::new(assets::DirAssets::new(dir))
  } else {
    Box::new(assets::EmptyAssets)
  };

  let package_info = PackageInfo {
    name: config
      .product_name
      .clone()
      .unwrap_or_else(|| "Tauri App".into()),
    version: config
      .version
      .as_deref()
      .unwrap_or("0.1.0")
      .parse()
      .map_err(|e| format!("invalid config version: {e}"))?,
    authors: "",
    description: "",
    crate_name: "tauri-ffi",
  };

  let global_api_scripts =
    (config.app.with_global_tauri && !GLOBAL_API_SCRIPTS.is_empty()).then_some(GLOBAL_API_SCRIPTS);

  // `Image::new` borrows the pixels; the context needs a `'static` icon, so the
  // host-provided copy is handed over with `to_owned`.
  let default_window_icon = default_window_icon
    .as_ref()
    .map(|(rgba, width, height)| tauri::image::Image::new(rgba, *width, *height).to_owned());

  let context = tauri::Context::<TauriRuntime>::new(
    config,
    assets,
    default_window_icon,
    app_icon,
    package_info,
    Pattern::Brownfield,
    authority,
    global_api_scripts,
  );

  // Serialized event stream: run events, subscribed events and invokes all
  // flow through one queue consumed by `tauri_events_next`.
  let (tx, rx) = mpsc::channel::<String>();

  let invoke_tx = tx.clone();
  let menu_tx = tx.clone();
  let mut builder = tauri::Builder::default()
    .invoke_handler(move |invoke: tauri::ipc::Invoke<TauriRuntime>| {
      let command = invoke.message.command();
      if !commands.contains(command) {
        return false; // tauri reports "command not found" to the frontend
      }
      let _ = invoke_tx.send(invoke_message_json(&invoke, command, None));
      true
    })
    // All menu clicks (app, window and tray menus) funnel into the event queue.
    .on_menu_event(move |_app, event| {
      let message = serde_json::json!({ "type": "menu-event", "id": event.id().0.clone() });
      let _ = menu_tx.send(message.to_string());
    })
    .enable_macos_default_menu(macos_default_menu);

  #[cfg(any(windows, target_os = "linux"))]
  if any_thread {
    builder = builder.any_thread();
  }
  #[cfg(not(any(windows, target_os = "linux")))]
  let _ = any_thread; // rejected at `tauri_app_builder_set_any_thread` time

  for script in invoke_initialization_scripts {
    builder = builder.append_invoke_initialization_script(script);
  }
  if let Some(filter) = device_event_filter {
    builder = builder.device_event_filter(filter);
  }

  // Custom protocols. The asynchronous variant is the only one that fits the
  // queue: the request is posted with an opaque responder handle and the webview
  // thread returns immediately, while the host answers whenever it is ready
  // (`tauri_uri_scheme_respond`).
  for scheme in uri_scheme_protocols {
    let protocol_tx = tx.clone();
    let scheme_name = scheme.clone();
    builder =
      builder.register_asynchronous_uri_scheme_protocol(scheme, move |ctx, request, responder| {
        let _ = protocol_tx.send(protocol::uri_scheme_request_json(
          &scheme_name,
          &ctx,
          request,
          responder,
        ));
      });
  }

  if page_load_events {
    let page_load_tx = tx.clone();
    builder = builder.on_page_load(move |webview, payload| {
      let message = serde_json::json!({
        "type": "page-load",
        "webview": webview.label(),
        "url": payload.url().to_string(),
        "event": match payload.event() {
          tauri::webview::PageLoadEvent::Started => "started",
          tauri::webview::PageLoadEvent::Finished => "finished",
        },
      });
      let _ = page_load_tx.send(message.to_string());
    });
  }

  if webview_events {
    let webview_tx = tx.clone();
    builder = builder.on_webview_event(move |webview, event| {
      if let Some(event) = webview_event_json(event) {
        let message = serde_json::json!({
          "type": "webview-event",
          "label": webview.label(),
          "event": event,
        });
        let _ = webview_tx.send(message.to_string());
      }
    });
    // Only the macOS/iOS webviews report a content process death.
    #[cfg(any(target_os = "macos", target_os = "ios"))]
    {
      let terminate_tx = tx.clone();
      builder = builder.on_web_content_process_terminate(move |webview| {
        let message = serde_json::json!({
          "type": "webview-event",
          "label": webview.label(),
          "event": { "kind": "process-terminated" },
        });
        let _ = terminate_tx.send(message.to_string());
      });
    }
  }

  // Compiled-in first-party plugins (declared in Cargo.toml). Registering them
  // wires `plugin:<name>|<command>` invokes to the real Rust handlers and injects
  // each plugin's `window.__TAURI__.<name>` API script. Permissions are NOT granted
  // here: the host opts in per plugin via capabilities, and the manifests embedded by
  // build.rs make identifiers like `fs:default` resolvable at runtime (`dynamic-acl`).
  //
  // Two plugins are compiled in but not auto-activated because they need host-supplied
  // arguments and change process-wide behavior, so each sits behind its own FFI entry
  // point (`tauri_app_builder_enable_localhost` / `_enable_single_instance`) instead of
  // being forced on every app:
  //   * localhost       — `Builder::new(port)` requires a port to serve the frontend on.
  //   * single-instance — `init(callback)` requires a new-instance callback and makes the
  //                        process refuse to launch a second instance.
  // single-instance must be the first plugin registered: it aborts the launch of a second
  // instance, and no other plugin should have initialized by then.
  if single_instance {
    let instance_tx = tx.clone();
    builder = builder.plugin(tauri_plugin_single_instance::init(
      move |_app, args, cwd| {
        let message = serde_json::json!({ "type": "single-instance", "args": args, "cwd": cwd });
        let _ = instance_tx.send(message.to_string());
      },
    ));
  }
  if let Some(port) = localhost_port {
    builder = builder.plugin(tauri_plugin_localhost::Builder::new(port).build());
  }

  builder = builder
    .plugin(tauri_plugin_fs::init())
    .plugin(tauri_plugin_clipboard_manager::init())
    .plugin(tauri_plugin_dialog::init())
    .plugin(tauri_plugin_http::init())
    .plugin(tauri_plugin_notification::init())
    .plugin(tauri_plugin_os::init())
    .plugin(tauri_plugin_process::init())
    .plugin(tauri_plugin_opener::init())
    .plugin(tauri_plugin_shell::init())
    .plugin(tauri_plugin_upload::init())
    .plugin(tauri_plugin_websocket::init())
    .plugin(tauri_plugin_positioner::init())
    .plugin(tauri_plugin_persisted_scope::init())
    .plugin(tauri_plugin_deep_link::init())
    .plugin(tauri_plugin_sql::Builder::new().build())
    .plugin(tauri_plugin_store::Builder::new().build())
    .plugin(tauri_plugin_log::Builder::new().build())
    .plugin(tauri_plugin_global_shortcut::Builder::new().build())
    .plugin(tauri_plugin_window_state::Builder::new().build())
    .plugin(tauri_plugin_autostart::Builder::new().build())
    // stronghold's password KDF needs a salt path, only known once the app has
    // resolved its data directory — register it from the setup hook like a normal app.
    // Best-effort: stronghold is opt-in (via capability), so a failure to resolve the
    // data dir or attach the plugin must not prevent the app from starting.
    .setup(|app| {
      use tauri::Manager;
      match app.path().app_local_data_dir() {
        Ok(dir) => {
          let salt_path = dir.join("stronghold-salt.txt");
          if let Err(e) = app
            .handle()
            .plugin(tauri_plugin_stronghold::Builder::with_argon2(&salt_path).build())
          {
            eprintln!("tauri-ffi: stronghold plugin unavailable: {e}");
          }
        }
        Err(e) => eprintln!("tauri-ffi: stronghold disabled, no app data dir: {e}"),
      }
      Ok(())
    });

  // Config-gated (see `cli_configured` / `updater_configured` above).
  if updater_configured {
    builder = builder.plugin(tauri_plugin_updater::Builder::new().build());
  }
  if cli_configured {
    builder = builder.plugin(tauri_plugin_cli::init());
  }

  // Each plugin gets a `tauri::plugin::Builder` whose invoke handler funnels
  // into the same event queue, tagged with the plugin name.
  for plugin in plugins {
    let state::PluginState {
      name,
      init_script,
      commands: plugin_commands,
    } = plugin;
    let plugin_tx = tx.clone();
    let plugin_name = name.clone();
    // `plugin::Builder::new` wants a `&'static str`; a plugin is created once
    // for the life of the app, so a one-time leak is acceptable.
    let leaked_name: &'static str = Box::leak(name.into_boxed_str());
    let mut plugin_builder = tauri::plugin::Builder::<TauriRuntime>::new(leaked_name)
      .invoke_handler(move |invoke: tauri::ipc::Invoke<TauriRuntime>| {
        // tauri strips the `plugin:<name>|` prefix before dispatch, so
        // `command()` is the bare command name here.
        let command = invoke.message.command();
        if !plugin_commands.contains(command) {
          return false;
        }
        let _ = plugin_tx.send(invoke_message_json(&invoke, command, Some(&plugin_name)));
        true
      });
    if let Some(js) = init_script {
      plugin_builder = plugin_builder.js_init_script(js);
    }
    let plugin = plugin_builder
      .try_build()
      .map_err(|e| format!("invalid plugin `{leaked_name}`: {e}"))?;
    builder = builder.plugin(plugin);
  }

  let app = builder
    .build(context)
    .map_err(|e| format!("failed to build app: {e}"))?;

  let handle = app.handle().clone();

  let mut capabilities = if capabilities.is_empty() {
    vec![DEFAULT_CAPABILITY.to_string()]
  } else {
    capabilities
  };
  // Grant every registered plugin's default permission to all windows — the
  // host opted in by registering the plugin's commands.
  if !plugin_names.is_empty() {
    let permissions: Vec<String> = plugin_names
      .iter()
      .map(|n| format!("{n}:default"))
      .collect();
    capabilities.push(
      serde_json::json!({
        "identifier": "tauri-ffi-plugins-default",
        "description": "Grants FFI-registered plugin default permissions to all windows.",
        "windows": ["*"],
        "permissions": permissions,
      })
      .to_string(),
    );
  }
  for capability in capabilities {
    handle
      .add_capability(capability)
      .map_err(|e| format!("invalid capability: {e}"))?;
  }

  let id = state::insert(Entry::App(Arc::new(AppState {
    handle,
    rx: Mutex::new(rx),
    tx,
  })));
  state::LOCAL_APPS.with(|apps| apps.borrow_mut().insert(id, app));
  Ok(id)
}

/// Registers the invoke's resolver and serializes it into a queue message.
/// `plugin` is `Some` for plugin commands (adds a `"plugin"` field).
fn invoke_message_json(
  invoke: &tauri::ipc::Invoke<TauriRuntime>,
  command: &str,
  plugin: Option<&str>,
) -> String {
  let payload = match invoke.message.payload() {
    InvokeBody::Json(value) => value.clone(),
    // TODO(M1): raw (binary) payloads
    InvokeBody::Raw(_) => serde_json::Value::Null,
  };
  let resolver_id = state::insert(Entry::Resolver(invoke.resolver.clone()));
  let mut message = serde_json::json!({
    "type": "invoke",
    "id": resolver_id,
    "command": command,
    "payload": payload,
    "webview": invoke.message.webview_ref().label(),
  });
  if let Some(plugin) = plugin {
    message["plugin"] = serde_json::Value::String(plugin.to_string());
  }
  message.to_string()
}

/// Serializes a webview event for the queue, or `None` for variants added to
/// the (non-exhaustive) tauri enums after this was written.
fn webview_event_json(event: &tauri::WebviewEvent) -> Option<serde_json::Value> {
  let tauri::WebviewEvent::DragDrop(event) = event else {
    return None;
  };
  let value = match event {
    tauri::DragDropEvent::Enter { paths, position } => serde_json::json!({
      "kind": "drag-enter", "paths": paths, "x": position.x, "y": position.y
    }),
    tauri::DragDropEvent::Over { position } => serde_json::json!({
      "kind": "drag-over", "x": position.x, "y": position.y
    }),
    tauri::DragDropEvent::Drop { paths, position } => serde_json::json!({
      "kind": "drag-drop", "paths": paths, "x": position.x, "y": position.y
    }),
    tauri::DragDropEvent::Leave => serde_json::json!({ "kind": "drag-leave" }),
    _ => return None,
  };
  Some(value)
}

/// Synthesizes an ACL manifest granting a host plugin's commands. The default
/// permission `<name>:default` (referenced by the default capability) allows
/// every registered command, so `plugin:<name>|<command>` resolves at runtime.
fn plugin_manifest(plugin: &state::PluginState) -> Manifest {
  use tauri::utils::acl::manifest::{DefaultPermission, PermissionFile};
  use tauri::utils::acl::{Commands, Permission};

  let commands = plugin.commands.iter().cloned().collect();
  let permission = Permission {
    version: None,
    identifier: "allow-all".to_string(),
    description: None,
    commands: Commands {
      allow: commands,
      deny: Vec::new(),
    },
    scope: Default::default(),
    platforms: None,
  };
  let file = PermissionFile {
    default: Some(DefaultPermission {
      version: None,
      description: None,
      permissions: vec!["allow-all".to_string()],
    }),
    set: Vec::new(),
    permission: vec![permission],
    commands: Vec::new(),
  };
  Manifest::new(vec![file], None)
}

