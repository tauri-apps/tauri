/// Emits an event to all listeners (Rust, frontend and FFI subscribers).
/// `payload_json` must be valid JSON.
#[no_mangle]
pub unsafe extern "C" fn tauri_app_emit(
  app: u64,
  event: *const c_char,
  payload_json: *const c_char,
) -> i32 {
  catch(|| {
    let event = try_cstr!(event);
    let payload = try_cstr!(payload_json);
    let Some(app_state) = state::app(app) else {
      return fail(ERR_INVALID_HANDLE, "invalid app handle");
    };
    match app_state.handle.emit_str(event, payload.to_string()) {
      Ok(()) => OK,
      Err(e) => fail(ERR_GENERIC, format!("emit failed: {e}")),
    }
  })
}

/// Emits an event to every target with the given label.
#[no_mangle]
pub unsafe extern "C" fn tauri_app_emit_to(
  app: u64,
  label: *const c_char,
  event: *const c_char,
  payload_json: *const c_char,
) -> i32 {
  catch(|| {
    let label = try_cstr!(label);
    let event = try_cstr!(event);
    let payload = try_cstr!(payload_json);
    let Some(app_state) = state::app(app) else {
      return fail(ERR_INVALID_HANDLE, "invalid app handle");
    };
    match app_state
      .handle
      .emit_str_to(EventTarget::labeled(label), event, payload.to_string())
    {
      Ok(()) => OK,
      Err(e) => fail(ERR_GENERIC, format!("emit_to failed: {e}")),
    }
  })
}

/// Subscribes to an event (any target). Deliveries arrive on the event queue
/// as `{"type":"event","event":...,"id":...,"payload":...}`.
#[no_mangle]
pub unsafe extern "C" fn tauri_app_listen(
  app: u64,
  event: *const c_char,
  out_listener: *mut u32,
) -> i32 {
  catch(|| {
    let event = try_cstr!(event);
    if out_listener.is_null() {
      return fail(ERR_INVALID_ARG, "out_listener is null");
    }
    let Some(app_state) = state::app(app) else {
      return fail(ERR_INVALID_HANDLE, "invalid app handle");
    };
    let tx = app_state.tx.clone();
    let name = event.to_string();
    let listener_id = app_state.handle.listen_any(name.clone(), move |event| {
      let payload: serde_json::Value = serde_json::from_str(event.payload())
        .unwrap_or_else(|_| serde_json::Value::String(event.payload().to_string()));
      let message = serde_json::json!({
        "type": "event",
        "event": name,
        "id": event.id(),
        "payload": payload,
      });
      let _ = tx.send(message.to_string());
    });
    unsafe { *out_listener = listener_id };
    OK
  })
}

#[no_mangle]
pub extern "C" fn tauri_app_unlisten(app: u64, listener: u32) -> i32 {
  catch(|| {
    let Some(app_state) = state::app(app) else {
      return fail(ERR_INVALID_HANDLE, "invalid app handle");
    };
    app_state.handle.unlisten(listener);
    OK
  })
}

