// helpers

pub(crate) unsafe fn cstr<'a>(ptr: *const c_char) -> Result<&'a str, i32> {
  if ptr.is_null() {
    return Err(fail(ERR_INVALID_ARG, "unexpected null string argument"));
  }
  CStr::from_ptr(ptr)
    .to_str()
    .map_err(|_| fail(ERR_INVALID_ARG, "string argument is not valid UTF-8"))
}

macro_rules! try_cstr {
  ($ptr:expr) => {
    match unsafe { $crate::cstr($ptr) } {
      Ok(s) => s,
      Err(code) => return code,
    }
  };
}
pub(crate) use try_cstr;

/// Writes an owned, NUL-terminated copy of `value` to `out`; the caller
/// releases it with `tauri_string_free`.
pub(crate) fn write_owned_str(out: *mut *mut c_char, value: String) {
  let value = CString::new(value).unwrap_or_default();
  unsafe { *out = value.into_raw() };
}

