/// Borrowed pointer, valid until the next failing FFI call on this thread.
/// Returns null if no error has been recorded.
#[no_mangle]
pub extern "C" fn tauri_last_error_message() -> *const c_char {
  error::last_error_ptr()
}

/// Releases a string previously returned through a `char**` out param.
#[no_mangle]
pub unsafe extern "C" fn tauri_string_free(ptr: *mut c_char) {
  if !ptr.is_null() {
    drop(CString::from_raw(ptr));
  }
}

/// Drops a handle from the registry (builder, app or resolver).
#[no_mangle]
pub extern "C" fn tauri_handle_close(handle: u64) -> i32 {
  catch(|| {
    state::remove(handle);
    OK
  })
}

