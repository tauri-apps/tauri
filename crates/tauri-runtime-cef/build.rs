use std::{
  env, fs,
  path::{Path, PathBuf},
};

fn main() {
  println!("cargo:rerun-if-changed=build.rs");
  // exposed to the build scripts of crates depending on this one as `DEP_TAURI_RUNTIME_CEF_RUNTIME`,
  // which is how `tauri-build` detects that the application uses the CEF runtime.
  println!("cargo:runtime=cef");
  // The CEF binary distribution `cef-dll-sys` resolved for this build, downloading it when it
  // was missing, passed on to the build scripts of crates depending on this one as
  // `DEP_TAURI_RUNTIME_CEF_CEF_DIR`: where the framework, `libcef` and the resources are.
  println!("cargo:rerun-if-env-changed=DEP_CEF_DLL_WRAPPER_CEF_DIR");
  let cef_dir = env::var("DEP_CEF_DLL_WRAPPER_CEF_DIR").ok();
  if let Some(cef_dir) = &cef_dir {
    println!("cargo:cef_dir={cef_dir}");
  }

  if env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("android") {
    // `cef-dll-sys` does not provide Android distributions yet, so `CEF_PATH` can also point
    // at one (or at a CEF build's `out/Release_GN_android_<arch>` directory).
    println!("cargo:rerun-if-env-changed=CEF_PATH");
    let cef_dir = cef_dir
      .or_else(|| env::var("CEF_PATH").ok())
      .map(PathBuf::from)
      .expect("set `CEF_PATH` to the CEF Android distribution, the directory with `cef.aar`");
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").unwrap());
    write_android_library(&cef_dir, &out_dir.join("android"));
    // `cef-dll-sys` skips its build script on Android.
    println!("cargo:rustc-link-search=native={}", cef_dir.display());
    println!("cargo:rustc-link-lib=dylib=cef");
    println!("cargo:rustc-link-lib=dylib=log");
  }
}

/// Writes the Gradle library module that adds CEF to the Android app.
///
/// `tauri-build` includes the module in the app's Gradle project through the
/// `DEP_TAURI_RUNTIME_CEF_ANDROID_LIBRARY_PATH` variable, like the Android libraries of plugins,
/// and applies its `tauri.app.gradle` script to the app.
///
/// `cef.aar` only holds the Chromium and CEF code. Chromium also uses androidx, Play Services
/// and Kotlin libraries, which the module declares as Maven dependencies so that Gradle picks one
/// version of each for the whole app.
fn write_android_library(cef_dir: &Path, module_dir: &Path) {
  let aar = cef_dir.join("cef.aar");
  let dependencies_file = cef_dir.join("cef_dependencies.txt");
  println!("cargo:rerun-if-changed={}", aar.display());
  println!("cargo:rerun-if-changed={}", dependencies_file.display());
  assert!(aar.exists(), "{} does not exist", aar.display());
  let dependencies = fs::read_to_string(&dependencies_file)
    .unwrap_or_else(|e| panic!("failed to read {}: {e}", dependencies_file.display()));

  // Lines are `group:artifact:version` dependencies, or `exclude group:artifact` for artifacts
  // that cef.aar holds Chromium's fork of. Other libraries still depend on those, so they are
  // excluded from every configuration of the app.
  let mut api = String::new();
  let mut excludes = String::new();
  for line in dependencies.lines() {
    let line = line.trim();
    if line.is_empty() || line.starts_with('#') {
      continue;
    }
    if let Some(coordinate) = line.strip_prefix("exclude ") {
      let (group, module) = coordinate
        .trim()
        .split_once(':')
        .unwrap_or_else(|| panic!("invalid line in {}: {line}", dependencies_file.display()));
      excludes.push_str(&format!(
        "\n    exclude(group: {}, module: {})",
        kotlin_string(group),
        kotlin_string(module)
      ));
    } else {
      api.push_str(&format!("\n    api({})", kotlin_string(line)));
    }
  }

  let build_gradle = format!(
    r#"// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
plugins {{
    id("com.android.library")
}}

android {{
    namespace = "app.tauri.cef"
    compileSdk = {COMPILE_SDK}

    defaultConfig {{
        minSdk = {MIN_SDK}
    }}
}}

dependencies {{
    api(files({})){api}
}}
"#,
    kotlin_string(&aar)
  );

  let app_gradle = format!(
    r#"// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
// Applied to the app module by tauri-build.
android {{
    // Chromium memory-maps these assets from the APK, which needs them stored uncompressed.
    androidResources.noCompress.addAll(["pak", "dat", "bin"])
}}

configurations.configureEach {{{excludes}
}}

if ((android.defaultConfig.minSdk ?: 0) < {MIN_SDK}) {{
    throw new GradleException("The CEF runtime needs Android {MIN_SDK} or newer. Set " +
        "`bundle > android > minSdkVersion` in tauri.conf.json to {MIN_SDK} or higher.")
}}
"#
  );

  let manifest_dir = module_dir.join("src").join("main");
  fs::create_dir_all(&manifest_dir).expect("failed to create the CEF Android library");
  write_if_changed(&module_dir.join("build.gradle.kts"), &build_gradle);
  write_if_changed(&module_dir.join("tauri.app.gradle"), &app_gradle);
  write_if_changed(
    &manifest_dir.join("AndroidManifest.xml"),
    "<manifest xmlns:android=\"http://schemas.android.com/apk/res/android\" />\n",
  );
  println!("cargo:android_library_path={}", module_dir.display());
}

/// The oldest Android version Chromium supports.
const MIN_SDK: u32 = 29;
/// The Android API level that the androidx releases CEF depends on are compiled against, which
/// must not be newer than the module's.
const COMPILE_SDK: u32 = 37;

fn kotlin_string(value: impl AsRef<Path>) -> String {
  let value = value.as_ref().to_string_lossy();
  format!("{value:?}").replace('$', "\\$")
}

// Gradle rebuilds when the files change, so keep their timestamps when the contents are the same.
fn write_if_changed(path: &Path, contents: &str) {
  if fs::read_to_string(path).ok().as_deref() != Some(contents) {
    fs::write(path, contents).unwrap_or_else(|e| panic!("failed to write {}: {e}", path.display()));
  }
}
